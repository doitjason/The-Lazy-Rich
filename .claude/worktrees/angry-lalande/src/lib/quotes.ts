export function getQuoteOfDay(): Quote {
    // 날짜를 기준으로 인덱스 생성 (시간 제외 날짜만)
    const today = new Date();
    const dateStamp = Math.floor(today.getTime() / (1000 * 60 * 60 * 24));
    const index = dateStamp % INVESTMENT_QUOTES.length;
    return INVESTMENT_QUOTES[index];
}
